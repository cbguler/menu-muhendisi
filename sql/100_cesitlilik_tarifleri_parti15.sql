-- DOGRULAMA
select r.ad, mk.sira as grup, r.mevsim_etiketi, count(rm.malzeme_id) as malzeme_sayisi
from receteler r
join mutfak_kategorileri mk on mk.id = r.mutfak_kategori_id
left join recete_malzemeleri rm on rm.recete_id = r.id
where r.isletme_id is null
  and r.ad in (
    'Fırında Dana But', 'Patatesli Dana Güveç', 'Kerevizli Tavuk Sote', 'Bezelyeli Dana Yahnisi', 'Taze Fasulyeli Tavuk Güveç',
    'Havuç ve Kereviz Çorbası', 'Naneli Bulgur Pilavı', 'Zeytinyağlı Patatesli Havuç', 'Zeytinyağlı Bezelyeli Havuç', 'Domatesli Patates Yemeği (Etsiz)',
